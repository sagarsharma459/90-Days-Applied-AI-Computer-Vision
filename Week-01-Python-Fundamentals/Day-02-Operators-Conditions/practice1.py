#### Exercise 1 — Arithmetic

total_production = 2000
no_of_trucks = 5
products_per_truck = total_production / no_of_trucks
rejected_products = 50
accepted_products = total_production - rejected_products
rejection_percentage = (rejected_products / total_production) * 100
print("Total Production:", total_production)
print("Number of Trucks:", no_of_trucks)
print("Products per Truck:", products_per_truck)
print("Rejected Products:", rejected_products)
print("Accepted Products:", accepted_products)
print("Rejection Percentage:", rejection_percentage, "%")
